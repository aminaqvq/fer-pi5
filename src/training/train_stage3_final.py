PROJECT_ROOT = Path(os.environ.get("FER_PROJECT_ROOT", r"/"))


def _p(*parts: str) -> str:
    return str(Path(*parts))


def resolve_project_path(value: str | None) -> Optional[Path]:
    if value is None or str(value).strip() in {"", "None", "none", "null"}:
        return None
    path = Path(str(value))
    return path if path.is_absolute() else PROJECT_ROOT / path


def choose_existing(candidates: Iterable[Path], *, name: str) -> Path:
    checked = []
    for path in candidates:
        checked.append(str(path))
        if path.exists():
            return path
    raise FileNotFoundError(
        f"No valid {name} found. Checked:\n" + "\n".join(checked)
    )


