REQUIRED_FILES = (
    CONFIG["train_csv"],
    CONFIG["val_csv"],
    CONFIG["test_csv"],
    CONFIG["pseudo_csv"],
    CONFIG["init_ckpt"],
)


def preflight() -> None:
    print("\n[Stage3 FINAL] Preflight")
    print(f"PROJECT_ROOT : {PROJECT_ROOT}")
    print(f"STAGE2_CKPT  : {STAGE2_BEST_CKPT}")
    print(f"PSEUDO_CSV   : {PSEUDO_STAGE2_FINAL}")

    missing = []
    for item in REQUIRED_FILES:
        path = resolve_project_path(str(item))
        if path is None or not path.exists():
            missing.append(str(path))
    if missing:
        raise FileNotFoundError(
            "Missing required files:\n" + "\n".join(missing)
        )

    lower_ckpt = str(CONFIG["init_ckpt"]).lower()
    if "weighted" in lower_ckpt or "clean_v2" in lower_ckpt:
        raise ValueError(
            "Stage3 final must not initialize from weighted_v2 / clean_v2 failed checkpoints."
        )

    if CONFIG["use_class_weights"] is not False:
        raise ValueError("Stage3 final uses balanced sampler, so use_class_weights must be False.")

    if CONFIG["batch_size"] != 7 * CONFIG["balanced_samples_per_class_per_batch"]:
        raise ValueError(
            "batch_size must equal 7 * balanced_samples_per_class_per_batch."
        )

    print("\n[Stage3 FINAL] Config audit:")
    for key in [
        "train_csv",
        "val_csv",
        "test_csv",
        "pseudo_csv",
        "init_ckpt",
        "epochs",
        "batch_size",
        "lr",
        "pseudo_loss_scale",
        "pseudo_rampup_epochs",
        "sampling_strategy",
        "balanced_samples_per_class_per_batch",
        "best_alias_name",
        "log_alias_name",
    ]:
        print(f"  {key}: {CONFIG.get(key)!r}")


def run() -> None:
    preflight()
    print("\n[Stage3 FINAL] Starting train_core.main(...)\n")
    train_core.main("stage3", CONFIG)


if __name__ == "__main__":
    run()
